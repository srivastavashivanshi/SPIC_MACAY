// Pulls the chapter's programmes from spicmacay.org into src/data/importedEvents.js.
// Usage: npm run import:spicmacay [-- "match text"]   (default match: "IIM Lucknow")
import { writeFile } from 'node:fs/promises';
import { importProgrammes } from '../server/spicmacayImport.js';

const match = process.argv[2] || 'IIM Lucknow';
const events = await importProgrammes({ match });
const body = [
  `// Generated by scripts/import-spicmacay.mjs from spicmacay.org's public programme feeds`,
  `// (matching "${match}") on ${new Date().toISOString().slice(0, 10)}. Re-run the script to refresh; edits here are overwritten.`,
  `export const importedEvents = ${JSON.stringify(events, null, 2)};`,
  '',
].join('\n');
await writeFile(new URL('../src/data/importedEvents.js', import.meta.url), body);
console.log(`Imported ${events.length} programmes matching "${match}":`);
for (const e of events) console.log(`  ${e.date}  ${e.title}`);
