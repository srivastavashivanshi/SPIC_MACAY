// Finds each artist's SPIC MACAY programmes in spicmacay.org's public feeds and writes
// src/data/appearances.js. Covers explorer artists and guests who performed at the chapter.
// Usage: npm run import:appearances
import { writeFile } from 'node:fs/promises';
import { FEEDS, fetchFeed } from '../server/spicmacayImport.js';
import { artists } from '../src/data/artists.js';
import { events } from '../src/data/events.js';

const bare = (name) => name.replace(/^(Pt\.|Ustad|Vidushi|Dr\.|Guru)\s+/, '').trim();
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const people = [
  ...artists.map((a) => ({ id: a.id, name: bare(a.name) })),
  ...events.filter((e) => e.artist && !e.artistId).map((e) => ({ id: slug(e.artist), name: e.artist })),
].filter((p, i, all) => all.findIndex((q) => q.id === p.id) === i);

const items = new Map();
for (const feed of FEEDS) for (const item of await fetchFeed(feed)) items.set(item.id, item);

const appearances = {};
for (const p of people) {
  // Exact performer name, or "… by [honorific] Name" in the title — not venues or longer names
  // ("Pt Ravi Shankar University", "Abdul Rashid Khan").
  const esc = p.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const byName = new RegExp(`\\bby\\s+(?:(?:pt|pandit|ustad|vidushi|dr|guru|smt|shri|sri)\\.?\\s+)?${esc}(?:\\s+(?:in|and|&)\\b|\\s*[,(]|$)`, 'i');
  const hits = [...items.values()]
    .filter((it) => (it.topArtists ?? []).some((a) => a.name.toLowerCase() === p.name.toLowerCase()) || byName.test(it.title))
    .map((it) => ({
      title: it.title,
      date: it.startDate.slice(0, 10),
      place: it.regions?.[0]?.name ?? it.location ?? '',
      url: it.ctaHref ? `https://spicmacay.org${it.ctaHref}` : '',
    }))
    .sort((a, b) => b.date.localeCompare(a.date));
  if (hits.length) appearances[p.id] = { name: p.name, total: hits.length, recent: hits.slice(0, 8) };
}

await writeFile(
  new URL('../src/data/appearances.js', import.meta.url),
  `// Generated by scripts/import-appearances.mjs from spicmacay.org's public programme feeds on ${new Date().toISOString().slice(0, 10)}.\n// Re-run to refresh; edits here are overwritten.\nexport const appearances = ${JSON.stringify(appearances, null, 2)};\n`,
);
console.log(`Scanned ${items.size} programmes.`);
for (const [id, a] of Object.entries(appearances)) console.log(`  ${a.name}: ${a.total}`);
